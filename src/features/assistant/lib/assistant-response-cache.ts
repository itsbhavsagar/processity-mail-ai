import type {
  AssistantContext,
  AssistantResponse,
} from "@/features/assistant/types/assistant-action";
import { PROMPT_VERSION } from "@/features/assistant/lib/assistant-system-prompt";
import { serializeAssistantContextForPrompt } from "@/features/assistant/lib/serialize-assistant-context";

const CACHE_TTL_MS = 5 * 60 * 1000;

interface CacheEntry {
  response: AssistantResponse;
  /** Model that produced this response, as reported by the API. */
  model?: string;
  expiresAt: number;
}

const responseCache = new Map<string, CacheEntry>();

/**
 * Most recent model the API reported. The model id can't go into the cache key
 * itself — this cache runs in the browser and ASSISTANT_MODEL is server-only
 * env, so it isn't readable here. Instead the server reports the model with
 * each response and we invalidate anything produced by a different one.
 */
let latestModel: string | undefined;

function hashString(value: string): string {
  let hash = 0;

  for (let index = 0; index < value.length; index += 1) {
    hash = (hash << 5) - hash + value.charCodeAt(index);
    hash |= 0;
  }

  return Math.abs(hash).toString(36);
}

export function buildAssistantCacheKey(
  prompt: string,
  context: AssistantContext,
): string {
  const payload = [
    PROMPT_VERSION,
    prompt.trim().toLowerCase(),
    serializeAssistantContextForPrompt(context),
  ].join("\n");

  return hashString(payload);
}

export function getCachedAssistantResponse(
  cacheKey: string,
): AssistantResponse | null {
  const entry = responseCache.get(cacheKey);
  if (!entry) {
    return null;
  }

  if (Date.now() > entry.expiresAt) {
    responseCache.delete(cacheKey);
    return null;
  }

  // Never serve a response generated by a different model than the one the
  // server is currently using.
  if (latestModel && entry.model !== latestModel) {
    responseCache.delete(cacheKey);
    return null;
  }

  return entry.response;
}

export function setCachedAssistantResponse(
  cacheKey: string,
  response: AssistantResponse,
  model?: string,
): void {
  // First fresh response from a new model invalidates everything cached from
  // the previous one.
  if (model && model !== latestModel) {
    responseCache.clear();
    latestModel = model;
  }

  responseCache.set(cacheKey, {
    response,
    model,
    expiresAt: Date.now() + CACHE_TTL_MS,
  });
}
